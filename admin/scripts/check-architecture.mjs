import { readFile, readdir } from 'node:fs/promises';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const sourceRoot = join(root, 'src');
const failures = [];

async function read(path) {
  return readFile(join(root, path), 'utf8');
}

async function sourceFiles(directory = sourceRoot) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      if (path === join(sourceRoot, 'test')) {
        continue;
      }
      files.push(...(await sourceFiles(path)));
    } else if (
      /\.(?:ts|tsx)$/.test(entry.name) &&
      !entry.name.endsWith('.test.ts') &&
      !entry.name.endsWith('.test.tsx') &&
      entry.name !== 'routeTree.gen.ts'
    ) {
      files.push(path);
    }
  }

  return files;
}

const packageJson = JSON.parse(await read('package.json'));
const dependencies = {
  ...packageJson.dependencies,
  ...packageJson.devDependencies,
};

for (const dependency of [
  '@radix-ui/react-dialog',
  '@radix-ui/react-separator',
  '@radix-ui/react-tooltip',
  '@tanstack/react-query',
  '@tanstack/react-router',
  '@tanstack/router-plugin',
  'tw-animate-css',
  'vite',
]) {
  if (!dependencies[dependency]) {
    failures.push(`package.json must retain ${dependency}`);
  }
}

for (const dependency of [
  '@tanstack/react-query-persist-client',
  '@tanstack/react-start',
  'axios',
  'next',
]) {
  if (dependencies[dependency]) {
    failures.push(`package.json must not add ${dependency} to the Admin Console`);
  }
}

const files = await sourceFiles();
const storageAllowlist = new Set([
  'src/features/preferences/store/preferences-store.ts',
  'src/i18n/index.ts',
]);

for (const absolutePath of files) {
  const path = relative(root, absolutePath);
  const content = await readFile(absolutePath, 'utf8');

  if (/\bfetch\s*\(/.test(content) && path !== 'src/http/client.ts') {
    failures.push(`${path} must use src/http/client.ts instead of fetch directly`);
  }

  if (
    /\b(?:localStorage|sessionStorage|indexedDB)\b/.test(content) &&
    !storageAllowlist.has(path)
  ) {
    failures.push(`${path} must not persist browser data outside the display-preference allowlist`);
  }

  if (/\bprocess\.env\b/.test(content)) {
    failures.push(`${path} must use validated import.meta.env configuration`);
  }

  if (/from\s+['"](?:\.\.\/)+(?:api|web)\//.test(content)) {
    failures.push(`${path} must not import another deployable unit's source`);
  }

  if (path.startsWith('src/routes/')) {
    for (const forbiddenImport of ['@/http/', '/services/', 'zustand']) {
      if (content.includes(forbiddenImport)) {
        failures.push(`${path} must remain a thin route and not import ${forbiddenImport}`);
      }
    }
    if (path !== 'src/routes/__root.tsx' && content.includes('@tanstack/react-query')) {
      failures.push(`${path} must remain a thin route and not import @tanstack/react-query`);
    }
  }
}

const routeTree = await read('src/routeTree.gen.ts');
if (!routeTree.includes('automatically generated by TanStack Router')) {
  failures.push('src/routeTree.gen.ts must remain generated by TanStack Router');
}

const componentsConfig = JSON.parse(await read('components.json'));
if (componentsConfig.style !== 'new-york') {
  failures.push('components.json must retain the shadcn/ui New York style');
}

const sidebar = await read('src/components/ui/sidebar.tsx');
for (const marker of ['SidebarProvider', 'SidebarInset', 'SidebarMenuButton']) {
  if (!sidebar.includes(marker)) {
    failures.push(`src/components/ui/sidebar.tsx must retain ${marker}`);
  }
}
if (sidebar.includes('document.cookie')) {
  failures.push('src/components/ui/sidebar.tsx must not write UI cookies from the static client');
}
for (const legacyMarker of ['w-[--sidebar-width', 'theme(spacing.4)']) {
  if (sidebar.includes(legacyMarker)) {
    failures.push(
      `src/components/ui/sidebar.tsx must use Tailwind 4 variable syntax instead of ${legacyMarker}`,
    );
  }
}

const consoleLayout = await read('src/components/layout/console-layout.tsx');
for (const marker of ['<SidebarProvider', '<AppSidebar', '<SidebarInset']) {
  if (!consoleLayout.includes(marker)) {
    failures.push(`console-layout.tsx must compose the official ${marker.slice(1)}`);
  }
}
if (consoleLayout.includes('<aside')) {
  failures.push('console-layout.tsx must not replace the shared Sidebar with a manual aside');
}

const globalStyles = await read('src/styles/globals.css');
for (const marker of [
  "@import 'tw-animate-css'",
  '--color-primary',
  '--color-sidebar-accent',
  '--brand: oklch(0.5 0.2 250)',
  '--brand: oklch(0.65 0.15 250)',
  '--color-brand-foreground',
  '--sidebar-accent: var(--brand-subtle)',
]) {
  if (!globalStyles.includes(marker)) {
    failures.push(`src/styles/globals.css must retain ${marker}`);
  }
}
for (const retiredBrandMarker of ['0.52 0.12 178', '0.68 0.11 178']) {
  if (globalStyles.includes(retiredBrandMarker)) {
    failures.push(
      `src/styles/globals.css must use Rhine blue instead of retired green ${retiredBrandMarker}`,
    );
  }
}

const staticOutputCheck = packageJson.scripts?.build ?? '';
for (const marker of ['check-static-output.mjs', 'check-bundle-budget.mjs']) {
  if (!staticOutputCheck.includes(marker)) {
    failures.push(`package.json build must run ${marker}`);
  }
}

if (failures.length > 0) {
  console.error('Admin Console architecture check failed:');
  for (const failure of failures) {
    console.error(`  ${failure}`);
  }
  process.exit(1);
}

console.log(
  `Admin Console architecture check passed (${files.length} production source files checked).`,
);
